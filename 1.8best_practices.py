def add_number(number_one, number_two):
    """Add two numbers and return the result.

    Args:
        number_one (int): The first number to add
        number_two (int): The second number to add

    Returns:
        int: The sum of the two numbers
    """
    result = number_one + number_two
    return result

def calculate_rectangle_area(Length, width):
    """Calculate the area of a rectangle
    Args:
        Length (int): The length of the rectangle
    """
    area = Length * width
    return area

# Example usage
sum_result = add_number(5, 3)
calc_rect_area = calculate_rectangle_area(10,20)
print(f"Sum of number_one and number_two: {sum_result}")
print(f"Rectangle Area: {calc_rect_area}")

